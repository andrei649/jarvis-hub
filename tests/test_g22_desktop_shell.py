"""G22 — the desktop shell: hub ownership (H171), Quick Entry (H179), decision
notifications (H181) and ``nerva://`` links (H183).

The policy modules are std-only Rust, so this suite compiles each one with
``rustc --test`` and runs its unit tests on any host with a Rust toolchain (no GTK or
WebKit needed). The static checks pin the security shape of the shell: the webview gets
no plugin, shell or filesystem permission; a link and a notification can only open a
HUD page; the shell never handles the hub's credentials.
"""

from __future__ import annotations

import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
TAURI = ROOT / "desktop" / "src-tauri"
SRC = TAURI / "src"
STD_ONLY = ("hub_policy", "hotkey", "notify", "deeplink")


@pytest.mark.skipif(sys.platform == "win32", reason="rustc test harness on POSIX CI hosts")
@pytest.mark.parametrize("module", STD_ONLY)
def test_the_policy_module_passes_its_unit_tests_under_rustc(module, tmp_path):
    rustc = shutil.which("rustc")
    if rustc is None:
        pytest.skip("rustc is not installed")
    out = tmp_path / f"{module}_tests"
    built = subprocess.run([rustc, "--edition", "2021", "--test", str(SRC / f"{module}.rs"), "-o", str(out)],
                           capture_output=True, text=True, timeout=300)
    assert built.returncode == 0, built.stderr
    ran = subprocess.run([str(out)], capture_output=True, text=True, timeout=120)
    assert ran.returncode == 0, ran.stdout + ran.stderr
    assert "test result: ok" in ran.stdout


@pytest.mark.parametrize("module", STD_ONLY)
def test_the_policy_modules_stay_std_only(module):
    """They are compiled alone above; a crate import would make that impossible."""
    text = (SRC / f"{module}.rs").read_text(encoding="utf-8")
    uses = re.findall(r"^\s*use\s+([a-z_]+)::", text, flags=re.M)
    assert set(uses) <= {"std", "super"}, uses


def test_the_webview_gets_only_the_shells_own_commands():
    cap = json.loads((TAURI / "capabilities" / "desktop.json").read_text(encoding="utf-8"))
    assert cap["windows"] == ["main", "floating"]
    assert cap["remote"]["urls"] == ["http://127.0.0.1:8080/v2", "http://127.0.0.1:8080/v2/*"]
    assert cap["permissions"] == [
        "allow-desktop-action", "allow-desktop-capabilities", "allow-desktop-listening", "allow-desktop-notify",
    ]
    build = (TAURI / "build.rs").read_text(encoding="utf-8")
    for command in ("desktop_action", "desktop_capabilities", "desktop_listening", "desktop_notify"):
        assert f'"{command}"' in build
    assert (TAURI / "permissions" / "autogenerated" / "desktop_notify.toml").is_file()


def test_no_shell_filesystem_or_opener_plugin_is_linked():
    cargo = (TAURI / "Cargo.toml").read_text(encoding="utf-8")
    for plugin in ("tauri-plugin-shell", "tauri-plugin-fs", "tauri-plugin-opener", "tauri-plugin-process",
                   "tauri-plugin-http", "tauri-plugin-notification"):
        assert plugin not in cargo, plugin
    for plugin in ("tauri-plugin-global-shortcut", "tauri-plugin-deep-link", "tauri-plugin-single-instance"):
        assert plugin in cargo, plugin


def test_the_nerva_scheme_is_registered_for_the_installer():
    conf = json.loads((TAURI / "tauri.conf.json").read_text(encoding="utf-8"))
    assert conf["plugins"]["deep-link"]["desktop"]["schemes"] == ["nerva"]


def test_links_and_notifications_only_open_a_hud_page_through_the_route_policy():
    main = (SRC / "main.rs").read_text(encoding="utf-8")
    open_hud = main.split("fn open_hud(", 1)[1].split("\nfn ", 1)[0]
    assert 'policy::allowed("main", &url)' in open_hud
    assert "navigate(url)" in open_hud
    handle = main.split("fn handle_link(", 1)[1].split("\nfn ", 1)[0]
    assert "deeplink::parse(raw)" in handle and "deeplink::hud_path(&link)" in handle
    # The raw link is untrusted and can be 34 KB: it is never echoed to the log.
    assert "{raw" not in handle and ", raw)" not in handle
    notify = main.split("fn show_notification(", 1)[1].split("\nfn ", 1)[0]
    assert "open_hud(&app2, path)" in notify
    for word in ("approve", "deny", "decide", "reqwest", "http"):
        assert word not in notify.lower(), word
    assert 'window.label() != "main"' in main.split("fn desktop_notify(", 1)[1].split("\nfn ", 1)[0]


def test_the_shell_never_handles_the_hubs_credentials():
    for name in ("hub.rs", "hub_policy.rs", "main.rs", "notify.rs", "deeplink.rs", "hotkey.rs"):
        text = (SRC / name).read_text(encoding="utf-8").lower()
        for word in ("x-admin-token", "x-user-token", "admin_token", "user_token", "jarvis_admin"):
            assert word not in text, (name, word)


def test_the_hub_is_started_like_start_sh_and_the_hud_waits_for_readyz():
    hub = (SRC / "hub.rs").read_text(encoding="utf-8")
    assert '.arg("serve.py")' in hub
    assert 'command.env("JARVIS_HUD", "v2")' in hub
    policy = (SRC / "hub_policy.rs").read_text(encoding="utf-8")
    assert "GET /readyz HTTP/1.1" in policy
    main = (SRC / "main.rs").read_text(encoding="utf-8")
    start = main.split("fn start_hub_then_hud(", 1)[1].split("\nfn ", 1)[0]
    assert start.index("owner.ensure()") < start.index("open_windows(&opener)")
    assert "owner.release()" in main.split(".run(|app, event|", 1)[1]


def test_quick_entry_only_focuses_the_composer():
    main = (SRC / "main.rs").read_text(encoding="utf-8")
    quick = main.split("fn quick_entry(", 1)[1].split("\nfn ", 1)[0]
    assert "nerva-desktop-quick-entry" in quick
    desktop = (ROOT / "frontend" / "src" / "desktop.tsx").read_text(encoding="utf-8")
    hook = desktop.split("export function useQuickEntryFocus", 1)[1].split("export ", 1)[0]
    assert "focus()" in hook and "apiPost" not in hook and "invoke" not in hook
