@contextmanager
def widest_orchestrator(root: str, extra_settings: dict | None = None):
    """The coordinator's real ToolRPC wiring with every optional tool switched on, and
    ``extra_settings`` (a host variant) on top.

    ``browser_run`` also needs Playwright, a Chromium and the enforcing kernel on this
    host; what is pinned here is its registration, so the readiness probe answers yes.
    A composed kernel manager takes an owner directory under ``code_sessions`` and sweeps
    that root on construction, so here that root is under ``root``, never the real data
    root (``--update`` runs outside pytest's temporary ``JARVIS_HOME``). No interpreter
    is started: composition launches nothing.

    ``orch.registrars`` maps each file that called ``register_tool`` during the wiring to
    the tools it registered (the last registration of a name wins), which is what a
    module-index row for that file may name as its tools."""
    from agents.core import browser_runtime, paths
    from agents.core.autonomy_coordinator import AutonomyCoordinator

    keys = (*ENV, "JARVIS_FILE_ROOTS")
    saved = {key: os.environ.get(key) for key in keys}
    ready = browser_runtime.local_browser_ready
    data_path = paths.data_path
    os.environ.update(ENV)
    os.environ["JARVIS_FILE_ROOTS"] = root
    browser_runtime.local_browser_ready = lambda **_kw: True
    paths.data_path = lambda *parts: (Path(root) / ".data" / Path(*parts) if parts == ("code_sessions",)
                                      else data_path(*parts))
    settings = {**SETTINGS, **(extra_settings or {})}
    try:
        orch = SimpleNamespace(agents={}, settings=settings,
                               get_setting=lambda key, default=None: settings.get(key, default))
        registered_by = {}
        register = ToolRPCServer.register_tool

        @functools.wraps(register)
        def recording(self, name, *args, **kwargs):
            caller = Path(sys._getframe(1).f_code.co_filename).resolve()
            registered_by[name] = caller.relative_to(REPO).as_posix() if caller.is_relative_to(REPO) else str(caller)
            return register(self, name, *args, **kwargs)

        ToolRPCServer.register_tool = recording
        try:
            orch.agent_tool_runtime = AutonomyCoordinator(orch)._wire_agent_tool_runtime()
        finally:
            ToolRPCServer.register_tool = register
        orch.registrars = {}
        for tool in orch.tool_rpc.tools(live=False):
            orch.registrars.setdefault(registered_by[tool["name"]], set()).add(tool["name"])
        yield orch
    finally:
        browser_runtime.local_browser_ready = ready
        paths.data_path = data_path
        for key, value in saved.items():
            if value is None:
                os.environ.pop(key, None)
            else:
                os.environ[key] = value


def surface(orch) -> list[dict]:
    """One row per registered tool: what the model is offered, and how the capability
    board (the open ``/api/metrics/capabilities`` view) labels it."""
    from agents.core.observability.capability_registry import snapshot

    server = orch.tool_rpc
    labels = {row["detail"]["tool"]: row for row in snapshot(orch, live_schemas=False)["capabilities"]
              if row["kind"] == "tool"}
    rows = []
    for tool in server.tools(live=False):
        name = tool["name"]
        label = labels.get(name)
        rows.append({
            "name": name,
            "gated": tool["gated"],
            "capability_id": tool.get("capability_id"),
            "untrusted_output": tool.get("untrusted_output") is True,
            # H296: these rows are narrowed to the install at runtime (the static row is
            # what is declared; the override can only narrow it).
            "live_overrides": server._tools[name].get("schema_overrides") is not None,
            "risk": label["risk"] if label else None,
            "rollback": label["rollback"] if label else None,
            "description": tool["description"],
            "input_schema": tool["input_schema"],
        })
    return rows


def variant_rows(base: list[dict], rows: list[dict]) -> list[dict]:
    """The rows a host variant changes against the base registry, in registry order."""
    pinned = {row["name"]: row for row in base}
    return [row for row in rows if row != pinned.get(row["name"])]


def _schema_properties(schema) -> set[str]:
    """Every property name an input schema declares, nested ones (an item's fields) too."""
    found = set()
    stack = [schema]
    while stack:
        node = stack.pop()
        if isinstance(node, dict):
            if isinstance(node.get("properties"), dict):
                found.update(node["properties"])
            stack.extend(node.values())
        elif isinstance(node, list):
            stack.extend(node)
    return found


def tool_properties(rows: list[dict], variants: dict[str, list[dict]]) -> dict[str, set[str]]:
    """Tool → every input property it declares, in the base registry or any host variant."""
    props = {row["name"]: _schema_properties(row["input_schema"]) for row in rows}
    for changed in variants.values():
        for row in changed:
            props.setdefault(row["name"], set()).update(_schema_properties(row["input_schema"]))
    return props


def retire(previous: dict | None, rows: list[dict], variants: dict[str, list[dict]]) -> dict:
    """The names that left the surface, as ``--update`` records them in the snapshot's
    ``retired``: every tool the previous snapshot had and the registry no longer has, and,
    per registered tool, every input property it no longer declares — kept from one update
    to the next, dropped only when the name comes back (H325 review r5). The hand-written
    docs are checked against it: a doc that still names a retired name fails, so a tool or
    a parameter renamed in code cannot leave its old name standing in the prose."""
    previous = previous or {}
    before = previous.get("retired", {})
    old = tool_properties(previous.get("tools", []),
                          {name: v["tools"] for name, v in previous.get("variants", {}).items()})
    now = tool_properties(rows, variants)
    tools = (set(before.get("tools", ())) | set(old)) - set(now)
    properties = {}
    for name in sorted(now):
        gone = (set(before.get("properties", {}).get(name, ())) | old.get(name, set())) - now[name]
        if gone:
            properties[name] = sorted(gone)
    return {"tools": sorted(tools), "properties": properties}


def render_table(rows: list[dict], variants: dict[str, list[dict]]) -> str:
    lines = [
        BEGIN,
        "",
        "| Tool | Gate | Risk | Rollback | Output | Schema | Capability |",
        "|---|---|---|---|---|---|---|",
    ]
    for row in rows:
        schema = "narrowed live" if row["live_overrides"] else "static"
        hosts = [name for name, changed in variants.items() if row["name"] in {r["name"] for r in changed}]
        if hosts:
            schema += "; other shape per host: " + ", ".join(f"`{name}`" for name in hosts)
        lines.append("| `{name}` | {gate} | {risk} | {rollback} | {output} | {schema} | `{cap}` |".format(
            name=row["name"],
            gate="gated" if row["gated"] else "ungated",
            risk=row["risk"],
            rollback=row["rollback"]["mode"],
            output="untrusted" if row["untrusted_output"] else "trusted",
            schema=schema,
            cap=row["capability_id"],
        ))
    for name, changed in variants.items():
        tools = ", ".join(f"`{row['name']}`" for row in changed)
        lines.append(f"\nHost variant `{name}` ({VARIANT_WHEN[name]}): {tools} is offered another "
                     "description and schema, pinned whole in the snapshot's `variants`.")
    lines += ["", END]
    return "\n".join(lines)


def _generated_block(text: str) -> str | None:
    start, end = text.find(BEGIN), text.find(END)
    if start < 0 or end < start:
        return None
    return text[start:end + len(END)]


