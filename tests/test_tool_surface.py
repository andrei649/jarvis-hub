def test_the_job_toolsets_catalog_names_registered_tools(widest):
    from agents.core.job_toolsets import CATALOG, catalog

    orch, rows = widest
    names = {row["name"] for row in rows}
    listed = {tool for tools in CATALOG.values() for tool in tools}
    assert sorted(listed - names - set(UNBUILT_TOOLS)) == []
    # An unbuilt reservation is still unbuilt (else it belongs in the registry check)…
    assert not set(UNBUILT_TOOLS) & names
    # …and the catalog says so at run time instead of offering it.
    unavailable = {row["id"] for row in catalog(orch.tool_rpc) if not row["available"]}
    assert unavailable == {group for group, tools in CATALOG.items() if set(tools) & set(UNBUILT_TOOLS)}


def _write_update() -> None:
    with tempfile.TemporaryDirectory() as root, widest_orchestrator(root) as orch:
        rows = surface(orch)
    SNAPSHOT.write_text(json.dumps({"tools": rows}, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    text = ARCHITECTURE.read_text(encoding="utf-8")
    block = _generated_block(text)
    if block is None:
        raise SystemExit("docs/ARCHITECTURE.md has no tool-surface markers to fill")
    ARCHITECTURE.write_text(text.replace(block, render_table(rows)), encoding="utf-8")
    print(f"wrote {SNAPSHOT} and the tool table in {ARCHITECTURE}")


if __name__ == "__main__":
    if "--update" in sys.argv:
        _write_update()
    else:
        print("usage: python tests/test_tool_surface.py --update")
