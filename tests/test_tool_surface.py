@pytest.mark.asyncio
async def test_the_capability_routes_do_not_call_an_ungated_writer_read_only(widest, monkeypatch):
    """Through both product doors: the open metrics view and the guarded inventory."""
    from agents.core.routers import analytics

    orch, _rows = widest
    monkeypatch.setattr(analytics, "get_orch", lambda: orch)
    for body in (json.loads((await analytics.metrics_capabilities()).body),
                 json.loads((await analytics.capabilities()).body)):
        records = {r["detail"]["tool"]: r for r in body["capabilities"] if r["kind"] == "tool"}
        for name, (risk, mode) in UNGATED_WRITERS.items():
            record = records[name]
            assert record["detail"]["gated"] is False
            assert (record["risk"], record["rollback"]["mode"]) == (risk, mode), name
            assert "No mutation" not in record["rollback"]["description"], name
        # The board tools are on the board at all now (they had no identity before).
        assert {n for n in records if n.startswith("kanban_")} == {
            n for n in UNGATED_WRITERS if n.startswith("kanban_")} | {
            "kanban_list", "kanban_show", "kanban_attachments"}
        for name in ("kanban_list", "kanban_show", "kanban_attachments", "file_read", "web_search",
                     "session_search", "echo", "skill_view"):
            assert (records[name]["risk"], records[name]["rollback"]["mode"]) == ("read_only", "none")


