# ── 1. the snapshot ──────────────────────────────────────────────────────────

def test_the_tool_surface_matches_the_snapshot(widest):
    _orch, rows = widest
    snap = json.loads(SNAPSHOT.read_text(encoding="utf-8"))
    assert [row["name"] for row in rows] == [row["name"] for row in snap["tools"]], (
        "A tool was added to or removed from the registry. " + UPDATE_HINT)
    for row, pinned in zip(rows, snap["tools"], strict=True):
        assert row == pinned, f"The surface of `{row['name']}` changed. " + UPDATE_HINT


def test_the_snapshot_covers_every_optional_tool(widest):
    _orch, rows = widest
    names = {row["name"] for row in rows}
    # The default-off ones too: file tools, speak, video, execute_code, clarify, the browser.
    assert {"file_write", "speak", "video_analyze", "execute_code", "clarify", "browser_run",
            "kanban_create", "memory", "todo"} <= names
    # Nothing in it depends on the temporary file root it was built under.
    assert "/tmp" not in json.dumps(rows) and tempfile.gettempdir() not in json.dumps(rows)


def test_the_snapshot_is_the_static_declaration_of_the_live_offer(widest):
    """The model is offered ``tools()``; it differs from the pinned static row only where a
    live H296 override narrows it, and only in the rows that declare one."""
    orch, rows = widest
    live = {tool["name"]: tool for tool in orch.tool_rpc.tools()}
    for row in rows:
        if not row["live_overrides"]:
            assert live[row["name"]]["description"] == row["description"]
            assert live[row["name"]]["input_schema"] == row["input_schema"]


