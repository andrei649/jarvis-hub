def test_every_register_tool_call_declares_its_effect():
    """Structural: a ``register_tool`` call in ``agents/`` that is not literally gated passes
    ``risk=`` (``None`` is allowed only where it is gated at run time), so a new ungated
    writer cannot fall back to the read-only label."""
    missing = []
    for path in sorted((REPO / "agents").rglob("*.py")):
        rel = path.relative_to(REPO)
        if rel.parts[:2] == ("agents", "web"):
            continue
        for node in ast.walk(ast.parse(path.read_text(encoding="utf-8"))):
            if not (isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute)
                    and node.func.attr == "register_tool"):
                continue
            keywords = {kw.arg: kw.value for kw in node.keywords}
            gated = keywords.get("gated")
            if isinstance(gated, ast.Constant) and gated.value is True:
                continue
            if "risk" not in keywords:
                missing.append(f"{rel}:{node.lineno}")
    assert missing == []


def _noop(args):
    return args


@pytest.mark.parametrize(("kwargs", "match"), [
    ({"rollback": RollbackContract(mode="cancel", description="x")}, "needs a declared risk"),
    ({"risk": "harmless"}, "risk must be one of"),
    ({"risk": "read_only", "gated": True}, "never read_only"),
    ({"risk": "read_only", "rollback": RollbackContract(mode="restore", description="x")}, "nothing to roll back"),
    ({"risk": "reversible"}, "declares how it is rolled back"),
    ({"risk": "sensitive", "rollback": RollbackContract(mode="none", description="x")}, "declares how"),
    ({"risk": "reversible", "rollback": {"mode": "restore"}}, "RollbackContract"),
])
def test_registration_refuses_a_dishonest_declaration(kwargs, match):
    server = ToolRPCServer()
    with pytest.raises(ValueError, match=match):
        server.register_tool("t", _noop, **kwargs)
    assert not server.allows("t")


@pytest.mark.asyncio
async def test_the_declaration_lives_beside_the_spec():
    from agents.core.autonomy.consent_registration import trusted_registration_key

    contract = RollbackContract(mode="compensate", description="Write it back.")
    server = ToolRPCServer()
    server.register_tool("w", _noop, consent_revision="t.v1")
    plain_key = trusted_registration_key("w", server._tools["w"])
    plain_rows = server.tools()
    server.register_tool("w", _noop, consent_revision="t.v1", risk="reversible", rollback=contract)
    assert server.declared_effect("w") == ("reversible", contract)
    # Neither the offer rows nor the consent registration's hash move.
    assert server.tools() == plain_rows and "risk" not in server.tools()[0]
    assert trusted_registration_key("w", server._tools["w"]) == plain_key is not None
    server.register_tool("w", _noop)               # re-registering without it clears it
    assert server.declared_effect("w") is None
    server.register_tool("w", _noop, risk="read_only")
    assert server.declared_effect("w") == ("read_only", None)
    assert await server.unregister_tool("w")
    assert server.declared_effect("w") is None and server.declared_effect("missing") is None


