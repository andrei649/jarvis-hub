@contextmanager
def widest_orchestrator(root: str):
    """The coordinator's real ToolRPC wiring with every optional tool switched on.

    ``browser_run`` also needs Playwright, a Chromium and the enforcing kernel on this
    host; what is pinned here is its registration, so the readiness probe answers yes."""
    from agents.core import browser_runtime
    from agents.core.autonomy_coordinator import AutonomyCoordinator

    keys = (*ENV, "JARVIS_FILE_ROOTS")
    saved = {key: os.environ.get(key) for key in keys}
    ready = browser_runtime.local_browser_ready
    os.environ.update(ENV)
    os.environ["JARVIS_FILE_ROOTS"] = root
    browser_runtime.local_browser_ready = lambda **_kw: True
    settings = dict(SETTINGS)
    try:
        orch = SimpleNamespace(agents={}, settings=settings,
                               get_setting=lambda key, default=None: settings.get(key, default))
        orch.agent_tool_runtime = AutonomyCoordinator(orch)._wire_agent_tool_runtime()
        yield orch
    finally:
        browser_runtime.local_browser_ready = ready
        for key, value in saved.items():
            if value is None:
                os.environ.pop(key, None)
            else:
                os.environ[key] = value


def surface(orch) -> list[dict]:
    """One row per registered tool: what the model is offered, and how the capability
    board (the open ``/api/metrics/capabilities`` view) labels it."""
    from agents.core.observability.capability_registry import snapshot

    server = orch.tool_rpc
    labels = {row["detail"]["tool"]: row for row in snapshot(orch, live_schemas=False)["capabilities"]
              if row["kind"] == "tool"}
    rows = []
    for tool in server.tools(live=False):
        name = tool["name"]
        label = labels.get(name)
        rows.append({
            "name": name,
            "gated": tool["gated"],
            "capability_id": tool.get("capability_id"),
            "untrusted_output": tool.get("untrusted_output") is True,
            # H296: these rows are narrowed to the install at runtime (the static row is
            # what is declared; the override can only narrow it).
            "live_overrides": server._tools[name].get("schema_overrides") is not None,
            "risk": label["risk"] if label else None,
            "rollback": label["rollback"] if label else None,
            "description": tool["description"],
            "input_schema": tool["input_schema"],
        })
    return rows


def render_table(rows: list[dict]) -> str:
    lines = [
        BEGIN,
        "",
        "| Tool | Gate | Risk | Rollback | Output | Schema | Capability |",
        "|---|---|---|---|---|---|---|",
    ]
    for row in rows:
        lines.append("| `{name}` | {gate} | {risk} | {rollback} | {output} | {schema} | `{cap}` |".format(
            name=row["name"],
            gate="gated" if row["gated"] else "ungated",
            risk=row["risk"],
            rollback=row["rollback"]["mode"],
            output="untrusted" if row["untrusted_output"] else "trusted",
            schema="narrowed live" if row["live_overrides"] else "static",
            cap=row["capability_id"],
        ))
    lines += ["", END]
    return "\n".join(lines)


def _generated_block(text: str) -> str | None:
    start, end = text.find(BEGIN), text.find(END)
    if start < 0 or end < start:
        return None
    return text[start:end + len(END)]


