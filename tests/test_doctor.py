def _write_lock_pair(root: Path, name: str, *, stale: bool = False) -> None:
    src = root / f"{name}.txt"
    src.write_text(f"{name}-dep==1\n", encoding="utf-8")
    digest = hashlib.sha256(src.read_bytes()).hexdigest()
    if stale:
        digest = "0" * 64
    (root / f"{name}.lock").write_text(
        f"# AUTOGENERATED\n# source-sha256: {digest}\n{name}-dep==1 --hash=sha256:x\n",
        encoding="utf-8",
    )


