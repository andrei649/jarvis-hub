def test_doctor_is_stdlib_only_apart_from_bootstrap():
    import ast
    src = (repo_root / "scripts" / "doctor.py").read_text(encoding="utf-8")
    names = set()
    for node in ast.walk(ast.parse(src)):
        if isinstance(node, ast.Import):
            names.update(a.name.split(".")[0] for a in node.names)
        elif isinstance(node, ast.ImportFrom) and node.module and node.level == 0:
            names.add(node.module.split(".")[0])
    # `agents` is imported lazily inside a try/except (broken-install fallback) — the
    # only non-stdlib names at module level are `scripts` (bootstrap) and `agents`.
    assert names - set(sys.stdlib_module_names) <= {"scripts", "agents"}


