def test_data_root_falls_back_to_env_precedence_when_paths_is_unimportable(tmp_path, monkeypatch):
    import builtins
    real_import = builtins.__import__

    def broken(name, *a, **k):
        if name == "agents.core.paths":
            raise ImportError("broken install")
        return real_import(name, *a, **k)

    monkeypatch.setattr(builtins, "__import__", broken)
    assert doctor.resolve_data_root(tmp_path, {}) == tmp_path / "memory_logs"
    assert doctor.resolve_data_root(tmp_path, {"JARVIS_MEMORY_DIR": "/x/y"}) == Path("/x/y")


