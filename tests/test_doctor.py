def _hub_urls(seen):
    """The requests that went to the hub (not the loopback runtime probes)."""
    urls = [getattr(u, "full_url", u) for u in seen]
    return [u for u in urls if u.endswith(("/readyz", "/api/onboarding/command-center"))]


