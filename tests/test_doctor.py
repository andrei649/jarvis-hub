def test_healthy_install_is_green_and_exits_zero(healthy_root, capsys):
    report = doctor.run_doctor(healthy_root, opener=_opener(), version_info=(3, 12, 0, "final", 0))
    by = report.by_name()
    assert report.ok is True
    assert by["python"].reason == "python_ok:3.12"
    assert by["venv"].reason == "venv_ok"
    assert by["locks_in_sync"].reason == "locks_ok"
    assert by["bind_is_loopback"].reason == "loopback"
    assert by["data_root_writable"].reason == "writable"
    assert by["data_root_writable"].detail == str(healthy_root / "data")
    assert by["runtimes"].reason == "found:ollama"
    assert by["readyz"].reason == "ready"
    assert by["smoke"].status == doctor.SKIP and by["smoke"].reason == "skipped"
    assert [c.name for c in report.checks] == list(doctor.REQUIRED) + list(doctor.ADVISORY)


