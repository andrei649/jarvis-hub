def test_required_failure_fails_the_run_and_the_cli(healthy_root, monkeypatch, capsys):
    monkeypatch.setenv("JARVIS_HOST", "0.0.0.0")
    report = doctor.run_doctor(healthy_root, opener=_opener(), version_info=(3, 12, 0, "final", 0))
    assert report.ok is False
    assert report.by_name()["bind_is_loopback"].status == doctor.FAIL

    monkeypatch.setattr(doctor, "run_doctor",
                        lambda root, **kw: report)
    assert doctor.main(["--root", str(healthy_root), "--json"]) == 1
    payload = json.loads(capsys.readouterr().out)
    assert payload["ok"] is False
    names = {c["name"]: c for c in payload["checks"]}
    assert names["bind_is_loopback"]["reason"] == "non_loopback_without_token"

    text = doctor.format_report(report)
    assert "[FAIL] bind_is_loopback" in text
    assert "NOT healthy" in text


