def test_smoke_runs_only_on_request_and_names_failures(healthy_root):
    class Proc:
        def __init__(self, rc, out="", err=""):
            self.returncode, self.stdout, self.stderr = rc, out, err

    calls = []

    def ok_run(argv, **kw):
        calls.append(argv)
        return Proc(0, json.dumps({"ok": True, "agents": 12}))

    def bad_run(argv, **kw):
        return Proc(1, "", "Install smoke failed: /readyz returned 503\n")

    skipped = doctor.check_smoke(healthy_root, enabled=False, run=ok_run)
    assert skipped.status == doctor.SKIP and calls == []

    good = doctor.check_smoke(healthy_root, enabled=True, run=ok_run)
    assert (good.status, good.reason, good.detail) == (doctor.OK, "ok", "12 agents")
    assert calls[0][0] == str(bootstrap.venv_python(healthy_root))
    assert calls[0][1].endswith("install_smoke.py")

    bad = doctor.check_smoke(healthy_root, enabled=True, run=bad_run)
    assert (bad.status, bad.reason) == (doctor.WARN, "smoke_failed")
    assert "503" in bad.detail


