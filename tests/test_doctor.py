def test_lock_stale_and_missing_reasons(tmp_path):
    _write_lock_pair(tmp_path, "requirements")
    _write_lock_pair(tmp_path, "requirements-beta", stale=True)
    (tmp_path / "requirements-dev.txt").write_text("pytest\n", encoding="utf-8")  # no lock
    rows = {src: reason for src, _lock, reason in doctor.lock_status(tmp_path)}
    assert rows == {
        "requirements.txt": "ok",
        "requirements-beta.txt": "lock_stale",
        "requirements-dev.txt": "lock_missing",
    }
    check = doctor.check_locks(tmp_path)
    assert check.status == doctor.FAIL
    assert check.reason == "lock_stale:requirements-beta.lock"
    assert "lock_missing:requirements-dev.lock" in check.detail


