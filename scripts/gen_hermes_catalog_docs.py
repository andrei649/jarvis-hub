#!/usr/bin/env python3
"""Generate local metadata pages for every skill in the validated Hermes v2 pin.

This script reads only the local pin. It does not fetch or execute upstream
content, install a skill, or change the status of any skill awaiting review.
"""

from __future__ import annotations

import argparse
import os
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
OUTPUT_DIR = REPO / "docs/hermes/catalog"
GENERATED_MARKER = "<!-- Generated by scripts/gen_hermes_catalog_docs.py from hermes_pin_v2.json. -->"

if str(REPO) not in sys.path:
    sys.path.insert(0, str(REPO))

from agents.core.skills.importer import SkillImportError, _load_hermes_pin  # noqa: E402


def _blob_url(repository: str, commit: str, path: str) -> str:
    return f"https://github.com/{repository}/blob/{commit}/{path}"


def _source_header(pin) -> list[str]:
    base = f"https://github.com/{pin.repository}"
    return [
        f"- Release: [{pin.release_tag}]({base}/releases/tag/{pin.release_tag})",
        f"- Commit: [`{pin.commit}`]({base}/commit/{pin.commit})",
        f"- Tree: [`{pin.tree}`](https://api.github.com/repos/{pin.repository}/git/trees/{pin.tree})",
    ]


def _skill_page(pin, entry) -> str:
    lines = [
        GENERATED_MARKER,
        f"# {entry.slug}",
        "",
        "This page records pinned upstream source metadata. It does not contain the skill's",
        "instructions and does not establish that the skill is installed or executable in Nerva.",
        "",
        *_source_header(pin),
        f"- Upstream tier: **{entry.tier}** (`{entry.path.split('/')[0]}/`)",
        f"- Pinned SKILL.md: [`{entry.path}`]({_blob_url(pin.repository, pin.commit, entry.path)})",
        f"- SKILL.md SHA-256: `{entry.content_sha256}`",
        "",
        "## Pinned reference files",
        "",
    ]
    if entry.files:
        lines.extend(["| Upstream path | SHA-256 |", "| --- | --- |"])
        lines.extend(
            f"| [`{path}`]({_blob_url(pin.repository, pin.commit, path)}) | `{digest}` |"
            for path, digest in entry.files
        )
    else:
        lines.append("None in this pin.")
    lines.extend([
        "",
        "## Owner path in Nerva",
        "",
        f"Open **HUD → Skills Import**, choose the exact name `{entry.slug}` from the pinned",
        "catalog, and request import. Remote import requires admin access and `DEV_MODE=1`;",
        "the `skill.install` kernel decision can refuse it. An allowed import writes a",
        "`PENDING_REVIEW` copy. The owner must inspect its pending detail and approve the",
        "matching source fingerprint separately before executable activation. The upstream",
        "tier above describes the source repository, not Nerva's default skill bundle.",
        "",
        "[Back to the pinned catalog](README.md).",
        "",
    ])
    return "\n".join(lines)


def _index_page(pin) -> str:
    entries = sorted(pin.skills, key=lambda entry: entry.slug)
    references = sum(len(entry.files) for entry in entries)
    bundled = sum(entry.tier == "bundled" for entry in entries)
    lines = [
        GENERATED_MARKER,
        "# Pinned Hermes skill source catalog",
        "",
        "These are metadata pages generated solely from Nerva's validated local",
        "`hermes_pin_v2.json`. They do not redistribute SKILL.md or reference contents and",
        "do not show installation, use, execution, or owner approval.",
        "",
        *_source_header(pin),
        f"- Eligible pinned skills: **{len(entries)}** ({bundled} upstream bundled,",
        f"  {len(entries) - bundled} upstream optional); pinned references: **{references}**.",
        "",
        "The four productivity subtrees excluded under the separate Anthropic terms and",
        "the removed `blogwatcher` are outside this catalog. No excluded PDF subtree is",
        "redistributed here. Upstream tier does not imply installation in Nerva.",
        "",
        "## Owner workflow",
        "",
        "In **HUD → Skills Import**, select an exact pinned name below. Remote import needs",
        "admin access and `DEV_MODE=1`, then crosses `skill.install`. An allowed import",
        "stages a quarantined `PENDING_REVIEW` copy. The owner inspects pending detail and",
        "approves its exact fingerprint separately; a kernel GRANT alone does not make",
        "that copy executable. These pages document source identity, not activation.",
        "",
        "| Exact name | Upstream tier | References |",
        "| --- | --- | ---: |",
    ]
    lines.extend(
        f"| [`{entry.slug}`]({entry.slug}.md) | {entry.tier} | {len(entry.files)} |"
        for entry in entries
    )
    lines.append("")
    return "\n".join(lines)


def build_documents(pin) -> dict[str, str]:
    """Pure mapping of expected relative doc names to deterministic UTF-8 content."""
    return {"README.md": _index_page(pin), **{
        f"{entry.slug}.md": _skill_page(pin, entry) for entry in pin.skills
    }}


def _is_owned_page(path: Path) -> bool:
    """Only a regular, non-linked page with our exact first-line marker is ours."""
    if path.is_symlink() or not path.is_file():
        return False
    with path.open(encoding="utf-8") as stream:
        return stream.readline().rstrip("\n") == GENERATED_MARKER


def _drift(output: Path, expected: dict[str, str]) -> list[str]:
    if output.is_symlink():
        return [f"linked output directory: {output}"]
    if not output.is_dir():
        return [f"missing output directory: {output}"]
    problems = []
    for name, content in expected.items():
        path = output / name
        if path.is_symlink():
            problems.append(f"linked generated page: {path}")
        elif not path.is_file():
            problems.append(f"missing generated page: {path}")
        elif path.read_text(encoding="utf-8") != content:
            problems.append(f"stale generated page: {path}")
    for path in sorted(output.glob("*.md")):
        if path.name not in expected and _is_owned_page(path):
            problems.append(f"stale generated page: {path}")
    return problems


def _write(output: Path, expected: dict[str, str]) -> None:
    if output.is_symlink():
        raise OSError(f"linked output directory: {output}")
    output.mkdir(parents=True, exist_ok=True)
    for name, content in expected.items():
        path = output / name
        if path.is_symlink():
            raise OSError(f"linked generated page: {path}")
        if path.exists():
            if not path.is_file():
                raise OSError(f"non-file generated page: {path}")
            previous = path.read_text(encoding="utf-8")
            if previous == content:
                continue
            if not previous.startswith(GENERATED_MARKER + "\n"):
                raise OSError(f"refusing to replace unowned page: {path}")
        descriptor, temporary = tempfile.mkstemp(prefix=".catalog-page-", dir=output)
        try:
            with os.fdopen(descriptor, "w", encoding="utf-8", newline="\n") as stream:
                stream.write(content)
            os.replace(temporary, path)
        finally:
            if os.path.exists(temporary):
                os.unlink(temporary)
    # A removed/renamed pin entry leaves a former generated page behind. Remove
    # only our own marked regular pages; owner notes and links are untouched.
    for path in sorted(output.glob("*.md")):
        if path.name not in expected and _is_owned_page(path):
            path.unlink()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="report missing or stale generated pages")
    args = parser.parse_args(argv)
    try:
        expected = build_documents(_load_hermes_pin())
        if args.check:
            problems = _drift(OUTPUT_DIR, expected)
            if problems:
                for problem in problems:
                    print(problem, file=sys.stderr)
                return 1
            print(f"Hermes catalog docs current: {len(expected) - 1} skills")
        else:
            _write(OUTPUT_DIR, expected)
            print(f"Hermes catalog docs written: {len(expected) - 1} skills")
        return 0
    except (OSError, UnicodeError, SkillImportError) as exc:
        print(f"Hermes catalog docs error: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
