// 2. Perform Language Auto-Detection
function detectLocale() {
  const persisted = localStorage.getItem('hud.lang');
  if (persisted && (persisted === 'ro' || persisted === 'en')) {
    return persisted;
  }
  const browserLang = navigator.language || navigator.userLanguage || '';
  if (browserLang.toLowerCase().startsWith('ro')) {
    return 'ro';
  }
  return 'en';
}

// 3. Define Global Window Accessors
window.currentLocale = detectLocale();

window.setLocale = function (lang) {
  if (lang !== 'ro' && lang !== 'en') return;
  window.currentLocale = lang;
  localStorage.setItem('hud.lang', lang);
  document.documentElement.setAttribute('lang', lang);
  
  // Dispatch custom event to let React App trigger dynamic re-render
  window.dispatchEvent(new CustomEvent('jarvis:locale_changed', { detail: lang }));
  console.log('[i18n] Language updated to:', lang.toUpperCase());
};

// Sync HTML attribute on bootstrap
document.documentElement.setAttribute('lang', window.currentLocale);

// 4. Translate function helper
function _t(key) {
  const translations = LOCALES[window.currentLocale] || LOCALES['ro'];
  return translations[key] || key;
}

window._t = _t;
